'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { inspectDirectory } = require('../src/pack-validator.cjs');
const root = path.resolve(__dirname, '..');
const runId = 'roundtrip-' + Date.now();
const directory = path.join(root, 'test-results', runId);
const library = path.join(directory, '源图形库 中文');
fs.cpSync(path.join(root, 'examples/portable-demo'), library, { recursive: true });
const manifestPath = path.join(library, 'pack.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
manifest.assets[0].effects[0].required = true;
manifest.assets[0].effects[0].settings = [{ path: [{ matchName: 'ADBE Gaussian Blur 2-0001', occurrence: 1 }], valueType: 'number', value: 8 }];
manifest.assets[0].effects.push({ id: 'tint', matchName: 'ADBE Fill', required: true, target: 'output', settings: [{ path: [{ matchName: 'ADBE Fill-0002', occurrence: 1 }], valueType: 'color', value: [1, .6, .1, 1] }] });
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
const config = { runId, root: directory.replace(/\\/g, '/'), library: library.replace(/\\/g, '/'), exported: path.join(directory, '导出的 图形包').replace(/\\/g, '/'), copied: path.join(directory, '再复制的 图形包').replace(/\\/g, '/') };
fs.writeFileSync(path.join(root, 'test-results', 'roundtrip-config.json'), JSON.stringify(config, null, 2));
const result = inspectDirectory(library);
if (!result.canRegister || !result.allContractValid) throw new Error('Prepared fixture failed contract checks: ' + JSON.stringify(result.diagnostics));
console.log(JSON.stringify(config));
